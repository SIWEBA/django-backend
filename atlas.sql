-- =====================================================================
-- ESQUEMA POSTGRESQL + TIMESCALEDB — SISTEMA DE ESTACIONES METEOROLÓGICAS
-- Versión explicada. Léelo de arriba hacia abajo: cada bloque dice QUÉ
-- crea y POR QUÉ está diseñado así.
-- =====================================================================
--
-- MAPA GENERAL
--   1. Extensiones
--   2. Cuentas y acceso:  roles_sistema, usuarios
--   3. Estructura física: estaciones, subestaciones
--   4. Permisos:          roles_estacion, usuarios_estaciones
--                         (el PROPIETARIO es un rol, ya no una columna)
--   5. Autenticación de dispositivos: api_keys
--   6. Datos (hypertables): lecturas, telemetria_dispositivo
--   7. Función de ingesta: upsert_lecturas()
--   8. Compresión
--   9. Continuous aggregates: lecturas_hora, lecturas_dia
--  10. Pruebas manuales (comentadas)
--
-- REGLAS DE NEGOCIO (se aplican en la capa de API, no como columnas):
--  - lecturas: SIEMPRE públicas para lectura, sin autenticarse.
--  - telemetria_dispositivo: SIEMPRE privada (propietario o colaborador
--    con permiso sobre la estación).
--  - Escribir (agregar/editar/borrar) SIEMPRE requiere autenticación y
--    permiso, sin importar que la lectura sea pública.
--
-- CONVENCIÓN DE BORRADO: todas las llaves foráneas usan ON DELETE
-- RESTRICT. Nada se borra en cascada por accidente; para "dar de baja"
-- se usan los campos de estado (activo/activa/estado).
-- =====================================================================


-- =====================================================================
-- 1. EXTENSIONES
-- =====================================================================

-- TimescaleDB: convierte tablas de series de tiempo en "hypertables"
-- (particionadas por tiempo en chunks), con compresión y agregados
-- continuos. Es lo que hace rápido el manejo de millones de lecturas.
CREATE EXTENSION IF NOT EXISTS timescaledb;

-- citext: texto que ignora mayúsculas/minúsculas. Lo usamos en el
-- correo para que "Ana@mail.com" y "ana@mail.com" sean el mismo.
CREATE EXTENSION IF NOT EXISTS citext;


-- =====================================================================
-- 2. CUENTAS Y ACCESO
-- =====================================================================

-- Rol a nivel PLATAFORMA (soporte, gestión de cuentas). Nunca da acceso
-- a los datos de una estación por sí solo; eso lo controla el rol de
-- estación (sección 4).
CREATE TABLE roles_sistema (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  varchar(50) NOT NULL UNIQUE
);

INSERT INTO roles_sistema (nombre) VALUES ('admin'), ('usuario');

CREATE TABLE usuarios (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_sistema_id  smallint NOT NULL REFERENCES roles_sistema (id) ON DELETE RESTRICT,
    nombre          varchar(100) NOT NULL,
    correo          citext NOT NULL UNIQUE,     -- UNIQUE ya crea su índice
    contrasena      varchar(255) NOT NULL,      -- SOLO el hash (Django lo genera)
    activo          boolean NOT NULL DEFAULT true,
    fecha_registro  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_usuarios_rol_sistema ON usuarios (rol_sistema_id);


-- =====================================================================
-- 3. ESTRUCTURA FÍSICA: ESTACIONES Y SUBESTACIONES
-- =====================================================================

-- La estación es la unidad que le importa a la persona: nombre,
-- ubicación y donde ve sus datos.
--
-- Así hay UN solo lugar donde se decide quién puede qué en una estación.
CREATE TABLE estaciones (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            varchar(100) NOT NULL,
    ubicacion         varchar(255),
    latitud           decimal(10, 8),
    longitud          decimal(11, 8),
    modelo            varchar(100),
    estado            varchar(20) NOT NULL DEFAULT 'activa'
                        CHECK (estado IN ('activa', 'inactiva', 'mantenimiento')),
    ultima_conexion   timestamptz,
    fecha_creacion    timestamptz NOT NULL DEFAULT now()
);

-- Subestaciones: cada aparato físico dentro de una misma estación.
-- La mayoría de las estaciones tiene un solo aparato, así que tienen una
-- sola subestación, que se crea sola al dar de alta la estación. Solo
-- importa cuando una estación junta varios aparatos. Cada
-- subestación tiene su propia api_key y su propia telemetría.
CREATE TABLE subestaciones (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estacion_id     integer NOT NULL REFERENCES estaciones (id) ON DELETE RESTRICT,
    nombre          varchar(100) NOT NULL,
    activa          boolean NOT NULL DEFAULT true,
    fecha_creacion  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (estacion_id, nombre)     -- no repetir nombre dentro de una estación
);

-- (UNIQUE (estacion_id, nombre) ya sirve para buscar por estacion_id, por
-- lo que este índice es redundante; se conserva para coincidir con el
-- diagrama y se puede eliminar sin perder velocidad.)
CREATE INDEX idx_subestaciones_estacion ON subestaciones (estacion_id);


-- =====================================================================
-- 4. PERMISOS: ROLES DE ESTACIÓN Y USUARIOS <-> ESTACIONES
-- =====================================================================

-- Catálogo FIJO de roles dentro de una estación. Los ids están
-- definidos en el código de Django y no cambian:
--   1 = propietario    (control total, uno solo por estación)
--   2 = administrador  (gestiona lo que el código le permita)
--   3 = visor          (solo ve, incluida la telemetría privada)
-- Lo que cada rol puede hacer se define UNA vez en Django, no por
-- persona. Si luego hacen falta permisos sueltos, se agrega una tabla
-- de permisos sin romper esto (cambio aditivo).
CREATE TABLE roles_estacion (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  varchar(50) NOT NULL UNIQUE
);

INSERT INTO roles_estacion (id, nombre) VALUES
    (1, 'propietario'),
    (2, 'administrador'),
    (3, 'visor');

-- Como insertamos ids a mano, avanzamos el contador para que los
-- próximos roles (si algún día hay) no choquen con 1, 2, 3.
ALTER TABLE roles_estacion ALTER COLUMN id RESTART WITH 4;

-- Quién tiene acceso a qué estación, y con qué rol. Incluye al
-- propietario (fila con rol_estacion_id = 1) y a los colaboradores.
-- Es la tabla de la relación muchos-a-muchos Usuario <-> Estación
-- (el rombo "colabora" del diagrama de Chen).
CREATE TABLE usuarios_estaciones (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id        integer NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
    estacion_id       integer NOT NULL REFERENCES estaciones (id) ON DELETE RESTRICT,
    rol_estacion_id   smallint NOT NULL REFERENCES roles_estacion (id) ON DELETE RESTRICT,
    estado            varchar(20) NOT NULL DEFAULT 'activo'
                        CHECK (estado IN ('activo', 'inactivo', 'suspendido')),
    fecha_asignacion  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (usuario_id, estacion_id)     -- una persona tiene UN rol por estación
);

-- usuario_id ya lo cubre el UNIQUE de arriba (queda como redundante).
-- estacion_id sí es necesario: "¿quién tiene acceso a esta estación?".
CREATE INDEX idx_ue_usuario  ON usuarios_estaciones (usuario_id);
CREATE INDEX idx_ue_estacion ON usuarios_estaciones (estacion_id);
CREATE INDEX idx_ue_rol      ON usuarios_estaciones (rol_estacion_id);

-- REGLA 1: como máximo UN propietario por estación.
-- Índice único PARCIAL: solo cuenta las filas con rol 1 (propietario).
-- Los colaboradores no entran en esta restricción.
CREATE UNIQUE INDEX uq_ue_un_propietario
    ON usuarios_estaciones (estacion_id)
    WHERE rol_estacion_id = 1;

-- REGLA 2: como mínimo UN propietario activo por estación.
-- Un índice no puede garantizar que algo EXISTA, así que se usa un
-- "constraint trigger" diferido: se evalúa al final de la transacción
-- (COMMIT), no fila por fila. Gracias a eso se puede, dentro de una
-- misma transacción:
--   a) crear la estación y DESPUÉS insertar a su propietario, o
--   b) transferir la propiedad (quitar al dueño viejo y poner al nuevo).
-- Si al hacer COMMIT la estación queda sin propietario activo, falla.
CREATE FUNCTION fn_exigir_propietario()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_estacion integer;
BEGIN
    IF TG_TABLE_NAME = 'estaciones' THEN
        v_estacion := NEW.id;                       -- estación recién creada
    ELSE
        IF OLD.rol_estacion_id <> 1 THEN
            RETURN NULL;                            -- no era propietario: nada que validar
        END IF;
        v_estacion := OLD.estacion_id;              -- se tocó una fila de propietario
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM usuarios_estaciones
        WHERE estacion_id = v_estacion
          AND rol_estacion_id = 1
          AND estado = 'activo'
    ) THEN
        RAISE EXCEPTION 'La estación % debe tener un propietario activo', v_estacion
            USING ERRCODE = '23514';                -- check_violation
    END IF;

    RETURN NULL;   -- en triggers AFTER el valor de retorno se ignora
END;
$$;

-- Al CREAR una estación: debe terminar la transacción con propietario.
CREATE CONSTRAINT TRIGGER trg_estacion_con_propietario
    AFTER INSERT ON estaciones
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_exigir_propietario();

-- Al CAMBIAR o BORRAR la fila de un propietario: no puede quedar vacía.
CREATE CONSTRAINT TRIGGER trg_ue_conserva_propietario
    AFTER UPDATE OR DELETE ON usuarios_estaciones
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_exigir_propietario();

-- OJO al hacer pruebas manuales: insertar una estación SIN su fila de
-- propietario dentro de la misma transacción falla en el COMMIT. Es lo
-- esperado; ver el ejemplo de la sección 10.


-- =====================================================================
-- 5. API KEYS (autenticación de cada subestación hacia la API)
-- =====================================================================

CREATE TABLE api_keys (
    id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subestacion_id         integer NOT NULL REFERENCES subestaciones (id) ON DELETE RESTRICT,
    creado_por_usuario_id  integer NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
    -- SOLO el hash, igual que una contraseña: la llave en texto plano se
    -- muestra una vez al crearla y nunca se vuelve a leer.
    api_key                varchar(255) NOT NULL,
    -- Primeros caracteres de la llave, visibles para identificarla en la
    -- interfaz ("sk_ab12...") y para buscarla rápido en cada request.
    prefijo_visible        varchar(12) NOT NULL,
    activa                 boolean NOT NULL DEFAULT true,
    fecha_creacion         timestamptz NOT NULL DEFAULT now(),
    fecha_ultimo_uso       timestamptz,
    fecha_expiracion       timestamptz
);

CREATE INDEX idx_api_keys_subestacion ON api_keys (subestacion_id);
CREATE INDEX idx_api_keys_usuario     ON api_keys (creado_por_usuario_id);
CREATE INDEX idx_api_keys_prefijo     ON api_keys (prefijo_visible);


-- =====================================================================
-- 6. DATOS (HYPERTABLES)
-- =====================================================================

-- ---------------------------------------------------------------------
-- LECTURAS — SIEMPRE públicas para lectura.
-- ---------------------------------------------------------------------
-- Una sola fila por (estación, instante), sin importar cuántas
-- subestaciones aporten datos a ese instante. Cada subestación hace un
-- upsert parcial con upsert_lecturas() (sección 7), tocando solo las
-- columnas que le corresponden.
--
-- Todo en unidades del sistema métrico; la API convierte si hace falta.
--
-- fillfactor = 90: deja 10% libre en cada página de disco para que los
-- UPDATE del upsert sean "HOT" (no generan entradas nuevas en índices),
-- lo que reduce bloat. Funciona porque las columnas que se actualizan no
-- están indexadas. Se declara ANTES de create_hypertable para que todos
-- los chunks nazcan con este valor.
CREATE TABLE lecturas (
    estacion_id         integer NOT NULL REFERENCES estaciones (id) ON DELETE RESTRICT,
    fecha_hora          timestamptz NOT NULL,
    -- Temperatura exterior
    temp_ext            real,
    temp_max            real,
    temp_min            real,
    -- Humedad exterior
    hum_ext             real,
    -- Viento
    vel_viento          real,
    dir_viento          smallint,
    recorrido_viento    real,
    vel_max_viento      real,
    dir_vel_max         smallint,
    -- Lluvia
    lluvia              real,
    tasa_lluvia         real,
    -- Radiación solar
    rad_solar           real,
    energia_solar       real,
    rad_solar_max       real,
    -- Ultravioleta
    indice_uv           real,
    dosis_uv            real,
    uv_max              real,
    -- Presión
    presion_bar         real,
    -- Índices de confort y derivados
    punto_rocio         real,
    sensacion_termica   real,
    indice_calor        real,
    indice_thw          real,
    indice_thsw         real,
    evapotranspiracion  real,
    -- Interior
    temp_int            real,
    hum_int             real,
    -- Calidad de recepción y archivo
    recepcion_iss       real,
    int_archivo         smallint,
    PRIMARY KEY (estacion_id, fecha_hora)    -- Timescale exige que incluya el tiempo
) WITH (fillfactor = 90);

-- Particiona la tabla en chunks de 7 días. Las consultas por rango de
-- fechas solo tocan los chunks necesarios.
SELECT create_hypertable('lecturas', by_range('fecha_hora', INTERVAL '7 days'));

