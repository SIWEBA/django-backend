-- =====================================================================
-- Comprime los chunks viejos para ahorrar disco. NO borra nada: los
-- datos nunca se eliminan por antigüedad. UPDATE/DELETE sobre chunks
-- comprimidos funciona desde TimescaleDB 2.11 (más lento, descomprime
-- por lotes; relevante para datos tardíos).
--
-- segmentby agrupa las filas comprimidas por esa columna: las consultas
-- "de UNA estación" leen solo su segmento. orderby ordena dentro de él.
-- NOTA: en versiones recientes de TimescaleDB esta función se llama
-- add_columnstore_policy; la sintaxis actual sigue funcionando, pero
-- verifica contra la versión que instales.

ALTER TABLE lecturas SET (
    timescaledb.compress,
    timescaledb.compress_segmentby = 'estacion_id',
    timescaledb.compress_orderby   = 'fecha_hora DESC'
);
SELECT add_compression_policy('lecturas', compress_after => INTERVAL '90 days');

ALTER TABLE telemetria_dispositivo SET (
