SELECT add_compression_policy('telemetria_dispositivo', compress_after => INTERVAL '90 days');


-- =====================================================================
-- 9. CONTINUOUS AGGREGATES — datos pre-calculados para gráficas rápidas
-- =====================================================================
-- Sin ellos, "temperatura del último mes" escanea millones de filas
-- crudas. Con ellos, la API lee una tabla pequeña ya resumida.
--
-- ¿Se gestionan desde aquí? Sí: son objetos de la base de datos y se
-- crean con SQL. Django NO los crea ni refresca; solo los LEE.
--   * Crearlos en una migración con RunSQL y atomic = False (no pueden
--     correr dentro de una transacción).
--   * Mapearlos con un modelo managed = False (solo lectura).
--   * Las políticas de refresco las ejecuta TimescaleDB en segundo plano.
--
-- La API elige la fuente según el rango pedido:
--   <= 2 días -> lecturas (crudo) | <= 3 meses -> lecturas_hora | más -> lecturas_dia
--
-- Son públicos (derivan de lecturas). Los buckets de día son en UTC; para
-- "lluvia del día" en hora local, calcular desde lecturas_hora cuando
-- exista zona_horaria en estaciones.
--
-- Datos tardíos: la política solo refresca hacia atrás hasta start_offset.
-- Para datos más viejos, refrescar el rango a mano:
--   CALL refresh_continuous_aggregate('lecturas_hora', '2026-01-01', '2026-02-01');

-- ---------------------------------------------------------------------
-- Por hora
-- ---------------------------------------------------------------------
CREATE MATERIALIZED VIEW lecturas_hora
WITH (timescaledb.continuous) AS
SELECT
    estacion_id,
    time_bucket('1 hour', fecha_hora)        AS hora,
    avg(temp_ext)::real                      AS temp_prom,
    max(temp_ext)                            AS temp_max,
    min(temp_ext)                            AS temp_min,
    avg(hum_ext)::real                       AS hum_prom,
    avg(presion_bar)::real                   AS presion_prom,
    avg(vel_viento)::real                    AS viento_prom,
    max(vel_max_viento)                      AS racha_max,
    sum(lluvia)::double precision            AS lluvia_total,   -- double: evita error de redondeo al sumar
    max(tasa_lluvia)                         AS tasa_lluvia_max,
    avg(rad_solar)::real                     AS rad_solar_prom,
    max(indice_uv)                           AS uv_max,
    count(*)                                 AS num_lecturas
FROM lecturas
GROUP BY estacion_id, hora
WITH NO DATA;    -- se llena con la política, no al crearla (más rápido)

-- Refresca cada 30 min la ventana [ahora-3 días, ahora-1 hora].
SELECT add_continuous_aggregate_policy('lecturas_hora',
    start_offset      => INTERVAL '3 days',
    end_offset        => INTERVAL '1 hour',
    schedule_interval => INTERVAL '30 minutes');

CREATE INDEX idx_lecturas_hora_estacion ON lecturas_hora (estacion_id, hora DESC);

-- Compresión de la vista (compress_after debe ser mayor que start_offset).
ALTER MATERIALIZED VIEW lecturas_hora SET (timescaledb.compress = true);
SELECT add_compression_policy('lecturas_hora', compress_after => INTERVAL '30 days');

-- ---------------------------------------------------------------------
-- Por día (UTC)
-- ---------------------------------------------------------------------
-- Se calcula desde las lecturas CRUDAS y no desde la vista por hora:
-- el promedio de promedios horarios no es el promedio real si alguna
-- hora tuvo menos lecturas.
CREATE MATERIALIZED VIEW lecturas_dia
WITH (timescaledb.continuous) AS
SELECT
    estacion_id,
    time_bucket('1 day', fecha_hora)         AS dia,
    avg(temp_ext)::real                      AS temp_prom,
    max(temp_ext)                            AS temp_max,
    min(temp_ext)                            AS temp_min,
    avg(hum_ext)::real                       AS hum_prom,
    avg(presion_bar)::real                   AS presion_prom,
    avg(vel_viento)::real                    AS viento_prom,
    max(vel_max_viento)                      AS racha_max,
    sum(lluvia)::double precision            AS lluvia_total,
    max(tasa_lluvia)                         AS tasa_lluvia_max,
    avg(rad_solar)::real                     AS rad_solar_prom,
    max(indice_uv)                           AS uv_max,
    count(*)                                 AS num_lecturas
FROM lecturas
GROUP BY estacion_id, dia
WITH NO DATA;

SELECT add_continuous_aggregate_policy('lecturas_dia',
    start_offset      => INTERVAL '7 days',
    end_offset        => INTERVAL '1 day',
    schedule_interval => INTERVAL '1 hour');

CREATE INDEX idx_lecturas_dia_estacion ON lecturas_dia (estacion_id, dia DESC);


