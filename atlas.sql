-- ---------------------------------------------------------------------
-- TELEMETRÍA DE SUBESTACIONES — SIEMPRE privada.
-- ---------------------------------------------------------------------
-- Una fila por subestación por instante. Batería y señal son del aparato
-- físico, cada uno tiene la suya y nunca "chocan". La estación se
-- obtiene por JOIN con subestaciones, así no puede quedar inconsistente.
-- Es solo-inserción (sin upsert), por eso no necesita fillfactor.
CREATE TABLE telemetria_dispositivo (
    subestacion_id       integer NOT NULL REFERENCES subestaciones (id) ON DELETE RESTRICT,
    fecha_hora           timestamptz NOT NULL,
    bateria_porcentaje   real,
    bateria_voltaje      real,
    panel_solar_voltaje  real,
    senal_rssi           smallint,
    PRIMARY KEY (subestacion_id, fecha_hora)
);

SELECT create_hypertable('telemetria_dispositivo', by_range('fecha_hora', INTERVAL '7 days'));


-- =====================================================================
-- 7. FUNCIÓN DE INGESTA: upsert_lecturas(jsonb)
-- =====================================================================
-- PROBLEMA QUE RESUELVE: varias subestaciones escriben la MISMA fila
-- (misma estación, mismo instante), cada una con columnas distintas. Un
-- upsert normal haría que la segunda pisara con NULL lo que escribió la
-- primera.
--
-- CÓMO LO RESUELVE: recibe un lote (arreglo JSON) donde cada objeto trae
-- estacion_id, fecha_hora y SOLO las columnas que se midieron:
--
--   SELECT upsert_lecturas('[
--     {"estacion_id": 1, "fecha_hora": "2026-10-04T12:00:00Z",
--      "temp_ext": 24.5, "hum_ext": 61},
--     {"estacion_id": 1, "fecha_hora": "2026-10-04T12:00:00Z",
--      "temp_int": 27.1}
--   ]'::jsonb);
--
-- GARANTÍAS:
--  1. Columna ausente o null  -> se conserva lo que ya había (COALESCE).
--  2. Dos objetos del mismo lote con la misma (estación, fecha_hora) se
--     fusionan antes (el último valor no nulo gana). Sin esto, Postgres
--     lanza "ON CONFLICT DO UPDATE command cannot affect row a second time".
--  3. Una sola ida a la base por lote; atómico (todo o nada).
--  4. Devuelve cuántas filas distintas se insertaron o actualizaron.
--
-- LIMITACIÓN: no se puede borrar un valor enviando null. Para corregir
-- o borrar un dato usa un UPDATE explícito desde un endpoint de edición.
--
-- Desde Django:
--   with connection.cursor() as cur:
--       cur.execute("SELECT upsert_lecturas(%s::jsonb)", [json.dumps(lote)])
--       filas = cur.fetchone()[0]

CREATE OR REPLACE FUNCTION upsert_lecturas(p_lecturas jsonb)
RETURNS integer
LANGUAGE sql
AS $$
WITH entrada AS (
    -- Convierte el JSON en filas con la forma de la tabla lecturas.
    -- Las claves ausentes quedan en NULL. "ordinality" conserva el orden
    -- de llegada dentro del lote.
    SELECT t.*
    FROM jsonb_populate_recordset(NULL::lecturas, p_lecturas) WITH ORDINALITY AS t
),
fusionada AS (
    -- Une duplicados del lote: por cada columna toma el último valor NO
    -- nulo, según el orden de llegada.
    SELECT
        estacion_id,
        fecha_hora,
        (array_agg(temp_ext           ORDER BY ordinality DESC) FILTER (WHERE temp_ext           IS NOT NULL))[1] AS temp_ext,
        (array_agg(temp_max           ORDER BY ordinality DESC) FILTER (WHERE temp_max           IS NOT NULL))[1] AS temp_max,
        (array_agg(temp_min           ORDER BY ordinality DESC) FILTER (WHERE temp_min           IS NOT NULL))[1] AS temp_min,
        (array_agg(hum_ext            ORDER BY ordinality DESC) FILTER (WHERE hum_ext            IS NOT NULL))[1] AS hum_ext,
        (array_agg(vel_viento         ORDER BY ordinality DESC) FILTER (WHERE vel_viento         IS NOT NULL))[1] AS vel_viento,
        (array_agg(dir_viento         ORDER BY ordinality DESC) FILTER (WHERE dir_viento         IS NOT NULL))[1] AS dir_viento,
        (array_agg(recorrido_viento   ORDER BY ordinality DESC) FILTER (WHERE recorrido_viento   IS NOT NULL))[1] AS recorrido_viento,
        (array_agg(vel_max_viento     ORDER BY ordinality DESC) FILTER (WHERE vel_max_viento     IS NOT NULL))[1] AS vel_max_viento,
        (array_agg(dir_vel_max        ORDER BY ordinality DESC) FILTER (WHERE dir_vel_max        IS NOT NULL))[1] AS dir_vel_max,
        (array_agg(lluvia             ORDER BY ordinality DESC) FILTER (WHERE lluvia             IS NOT NULL))[1] AS lluvia,
        (array_agg(tasa_lluvia        ORDER BY ordinality DESC) FILTER (WHERE tasa_lluvia        IS NOT NULL))[1] AS tasa_lluvia,
        (array_agg(rad_solar          ORDER BY ordinality DESC) FILTER (WHERE rad_solar          IS NOT NULL))[1] AS rad_solar,
        (array_agg(energia_solar      ORDER BY ordinality DESC) FILTER (WHERE energia_solar      IS NOT NULL))[1] AS energia_solar,
        (array_agg(rad_solar_max      ORDER BY ordinality DESC) FILTER (WHERE rad_solar_max      IS NOT NULL))[1] AS rad_solar_max,
        (array_agg(indice_uv          ORDER BY ordinality DESC) FILTER (WHERE indice_uv          IS NOT NULL))[1] AS indice_uv,
        (array_agg(dosis_uv           ORDER BY ordinality DESC) FILTER (WHERE dosis_uv           IS NOT NULL))[1] AS dosis_uv,
        (array_agg(uv_max             ORDER BY ordinality DESC) FILTER (WHERE uv_max             IS NOT NULL))[1] AS uv_max,
        (array_agg(presion_bar        ORDER BY ordinality DESC) FILTER (WHERE presion_bar        IS NOT NULL))[1] AS presion_bar,
        (array_agg(punto_rocio        ORDER BY ordinality DESC) FILTER (WHERE punto_rocio        IS NOT NULL))[1] AS punto_rocio,
        (array_agg(sensacion_termica  ORDER BY ordinality DESC) FILTER (WHERE sensacion_termica  IS NOT NULL))[1] AS sensacion_termica,
        (array_agg(indice_calor       ORDER BY ordinality DESC) FILTER (WHERE indice_calor       IS NOT NULL))[1] AS indice_calor,
        (array_agg(indice_thw         ORDER BY ordinality DESC) FILTER (WHERE indice_thw         IS NOT NULL))[1] AS indice_thw,
        (array_agg(indice_thsw        ORDER BY ordinality DESC) FILTER (WHERE indice_thsw        IS NOT NULL))[1] AS indice_thsw,
        (array_agg(evapotranspiracion ORDER BY ordinality DESC) FILTER (WHERE evapotranspiracion IS NOT NULL))[1] AS evapotranspiracion,
        (array_agg(temp_int           ORDER BY ordinality DESC) FILTER (WHERE temp_int           IS NOT NULL))[1] AS temp_int,
        (array_agg(hum_int            ORDER BY ordinality DESC) FILTER (WHERE hum_int            IS NOT NULL))[1] AS hum_int,
        (array_agg(recepcion_iss      ORDER BY ordinality DESC) FILTER (WHERE recepcion_iss      IS NOT NULL))[1] AS recepcion_iss,
        (array_agg(int_archivo        ORDER BY ordinality DESC) FILTER (WHERE int_archivo        IS NOT NULL))[1] AS int_archivo
    FROM entrada
    GROUP BY estacion_id, fecha_hora
),
upsert AS (
    -- Inserta; si ya existe la (estación, fecha_hora), actualiza SOLO las
    -- columnas con valor nuevo (COALESCE conserva la anterior si viene NULL).
    INSERT INTO lecturas AS l (
        estacion_id, fecha_hora,
        temp_ext, temp_max, temp_min, hum_ext,
        vel_viento, dir_viento, recorrido_viento, vel_max_viento, dir_vel_max,
        lluvia, tasa_lluvia,
        rad_solar, energia_solar, rad_solar_max,
        indice_uv, dosis_uv, uv_max,
        presion_bar, punto_rocio, sensacion_termica,
        indice_calor, indice_thw, indice_thsw,
        evapotranspiracion, temp_int, hum_int, recepcion_iss, int_archivo
    )
    SELECT
        estacion_id, fecha_hora,
        temp_ext, temp_max, temp_min, hum_ext,
        vel_viento, dir_viento, recorrido_viento, vel_max_viento, dir_vel_max,
        lluvia, tasa_lluvia,
        rad_solar, energia_solar, rad_solar_max,
        indice_uv, dosis_uv, uv_max,
        presion_bar, punto_rocio, sensacion_termica,
        indice_calor, indice_thw, indice_thsw,
        evapotranspiracion, temp_int, hum_int, recepcion_iss, int_archivo
    FROM fusionada
    ON CONFLICT (estacion_id, fecha_hora) DO UPDATE SET
        temp_ext           = COALESCE(EXCLUDED.temp_ext,           l.temp_ext),
        temp_max           = COALESCE(EXCLUDED.temp_max,           l.temp_max),
        temp_min           = COALESCE(EXCLUDED.temp_min,           l.temp_min),
        hum_ext            = COALESCE(EXCLUDED.hum_ext,            l.hum_ext),
        vel_viento         = COALESCE(EXCLUDED.vel_viento,         l.vel_viento),
        dir_viento         = COALESCE(EXCLUDED.dir_viento,         l.dir_viento),
        recorrido_viento   = COALESCE(EXCLUDED.recorrido_viento,   l.recorrido_viento),
        vel_max_viento     = COALESCE(EXCLUDED.vel_max_viento,     l.vel_max_viento),
        dir_vel_max        = COALESCE(EXCLUDED.dir_vel_max,        l.dir_vel_max),
        lluvia             = COALESCE(EXCLUDED.lluvia,             l.lluvia),
        tasa_lluvia        = COALESCE(EXCLUDED.tasa_lluvia,        l.tasa_lluvia),
        rad_solar          = COALESCE(EXCLUDED.rad_solar,          l.rad_solar),
        energia_solar      = COALESCE(EXCLUDED.energia_solar,      l.energia_solar),
        rad_solar_max      = COALESCE(EXCLUDED.rad_solar_max,      l.rad_solar_max),
        indice_uv          = COALESCE(EXCLUDED.indice_uv,          l.indice_uv),
        dosis_uv           = COALESCE(EXCLUDED.dosis_uv,           l.dosis_uv),
        uv_max             = COALESCE(EXCLUDED.uv_max,             l.uv_max),
        presion_bar        = COALESCE(EXCLUDED.presion_bar,        l.presion_bar),
        punto_rocio        = COALESCE(EXCLUDED.punto_rocio,        l.punto_rocio),
        sensacion_termica  = COALESCE(EXCLUDED.sensacion_termica,  l.sensacion_termica),
        indice_calor       = COALESCE(EXCLUDED.indice_calor,       l.indice_calor),
        indice_thw         = COALESCE(EXCLUDED.indice_thw,         l.indice_thw),
        indice_thsw        = COALESCE(EXCLUDED.indice_thsw,        l.indice_thsw),
        evapotranspiracion = COALESCE(EXCLUDED.evapotranspiracion, l.evapotranspiracion),
        temp_int           = COALESCE(EXCLUDED.temp_int,           l.temp_int),
        hum_int            = COALESCE(EXCLUDED.hum_int,            l.hum_int),
        recepcion_iss      = COALESCE(EXCLUDED.recepcion_iss,      l.recepcion_iss),
        int_archivo        = COALESCE(EXCLUDED.int_archivo,        l.int_archivo)
    RETURNING 1
)
SELECT count(*)::integer FROM upsert;
$$;


